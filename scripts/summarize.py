#!/usr/bin/env python3
"""Generate docs/RESULTS.md (all result tables) from results/*.json.

    python3 scripts/summarize.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")


def load(n):
    with open(os.path.join(RES, n)) as f:
        return json.load(f)


def pct(v, d=2):
    return "–" if v is None else f"{100 * v:.{d}f}"


out = []
w = out.append
w("# Results\n")
w("_Auto-generated by `scripts/summarize.py` from `results/*.json`. Do not edit by hand._\n")
w("All numbers come from `./core/build/cdnopt experiment all`. Unless stated otherwise: 5,000 objects (34 GB), "
  "cache = 5% of catalog bytes, 40 epochs × 15,000 requests, α = β = 1, first 2 epochs excluded as warm-up. "
  "`*` marks oracles that use future knowledge (reference bounds, not deployable).\n")

# ---------------------------------------------------------------- compare --
c = load("compare.json")
w(f"## 1. Head-to-head ({c['seeds']} seeds per pattern)\n")
w("Benefit captured (%) = share of total caching benefit B = f·(α·cost + β·latency) served from the edge. "
  "This is the knapsack objective. Mean ± s.d. across seeds.\n")
keys = [a["key"] for a in c["patterns"][0]["algorithms"]]
names = {a["key"]: a["name"] for a in c["patterns"][0]["algorithms"]}
w("| Algorithm | " + " | ".join(p["pattern"] for p in c["patterns"]) + " |")
w("|---|" + "---:|" * len(c["patterns"]))
for k in keys:
    cells = []
    for p in c["patterns"]:
        a = next(x for x in p["algorithms"] if x["key"] == k)
        best = max(x["mean"]["benefitRatio"] for x in p["algorithms"] if not x["oracle"])
        s = f"{pct(a['mean']['benefitRatio'])} ± {pct(a['std']['benefitRatio'])}"
        cells.append(f"**{s}**" if (not a["oracle"] and a["mean"]["benefitRatio"] == best) else s)
    w(f"| {names[k]} | " + " | ".join(cells) + " |")
w("")
w("### Paired comparison: PACK-DP minus each algorithm (benefit, percentage points)\n")
w("Same catalog and trace per seed. Because seeds differ in catalog, this paired statistic is the fair test.\n")
w("| Algorithm | " + " | ".join(p["pattern"] for p in c["patterns"]) + " |")
w("|---|" + "---:|" * len(c["patterns"]))
total_w = total_n = 0
for k in keys:
    if k == "pack":
        continue
    cells = []
    for p in c["patterns"]:
        q = next(x for x in p["pairedVsPack"] if x["key"] == k)
        cells.append(f"{100 * q['meanDelta']:+.2f} ± {100 * q['stdDelta']:.2f} ({q['packWins']}/{q['runs']})")
        if k not in ("dp-oracle", "belady"):
            total_w += q["packWins"]
            total_n += q["runs"]
    w(f"| {names[k]} | " + " | ".join(cells) + " |")
w(f"\nPACK-DP wins **{total_w}/{total_n}** paired comparisons against deployable baselines.\n")

w("### All metrics: mixed traffic\n")
cols = [("benefitRatio", "Benefit %", True), ("hitRatio", "Hit %", True), ("byteHitRatio", "Byte hit %", True),
        ("costSavedPct", "$ saved %", False), ("avgLatencyMs", "Latency ms", False), ("originOffloadPct", "Offload %", False),
        ("burstHitRatio", "Flash-onset hit %", True), ("planMs", "Plan ms (total)", False), ("nsPerRequest", "ns/req", False)]
mixed = next(p for p in c["patterns"] if p["pattern"] == "mixed")
w("| Algorithm | " + " | ".join(cn[1] for cn in cols) + " |")
w("|---|" + "---:|" * len(cols))
for a in mixed["algorithms"]:
    row = []
    for k, _, isp in cols:
        v = a["mean"].get(k)
        row.append(pct(v, 1) if isp else ("–" if v is None else f"{v:.1f}" if k != "nsPerRequest" and k != "planMs" else f"{v:.0f}"))
    w(f"| {a['name']} | " + " | ".join(row) + " |")
w("")


# ------------------------------------------------------------------ sweeps --
def sweep_table(name, pattern, field, title, xfmt, isp=True):
    d = load(name + ".json")
    p = next(x for x in d["patterns"] if x["pattern"] == pattern)
    w(f"### {title}\n")
    w(f"{d['xLabel']}; {pattern} traffic; mean of {d['seeds']} seeds.\n")
    w("| Algorithm | " + " | ".join(xfmt(x) for x in d["x"]) + " |")
    w("|---|" + "---:|" * len(d["x"]))
    for s in p["series"]:
        vals = s["mean"][field]
        w(f"| {s['name']} | " + " | ".join(pct(v, 1) if isp else ("–" if v is None else f"{v:.0f}") for v in vals) + " |")
    w("")


w("## 2. Sweeps\n")
sweep_table("capacity", "mixed", "benefitRatio", "Benefit captured vs cache size", lambda x: f"{100 * x:g}%")
sweep_table("capacity", "zipf", "benefitRatio", "Benefit captured vs cache size (Zipf)", lambda x: f"{100 * x:g}%")
sweep_table("skew", "zipf", "benefitRatio", "Benefit captured vs Zipf skew", lambda x: f"s={x:g}")
sweep_table("flash", "flash", "burstHitRatio", "Hit ratio during flash-crowd onset epochs vs burst intensity", lambda x: f"{100 * x:.0f}%")
sweep_table("epoch", "drift", "benefitRatio", "Benefit vs epoch length (drift)", lambda x: f"{x / 1000:g}k")
sweep_table("epoch", "drift", "planMs", "Total planning time (ms) vs epoch length (drift)", lambda x: f"{x / 1000:g}k", isp=False)
sweep_table("weights", "zipf", "hitRatio", "Request hit ratio vs α (β = 1 − α)", lambda x: f"α={x:g}")
sweep_table("weights", "zipf", "byteHitRatio", "Byte hit ratio vs α (β = 1 − α)", lambda x: f"α={x:g}")
sweep_table("resolution", "zipf", "benefitRatio", "Benefit vs DP capacity resolution", lambda x: f"{x:g}")

# ---------------------------------------------------------------- ablation --
a = load("ablation.json")
w(f"## 3. Ablation ({a['seeds']} seeds): benefit minus full PACK-DP (pts)\n")
w("| Variant | " + " | ".join(p["pattern"] for p in a["patterns"]) + " |")
w("|---|" + "---:|" * len(a["patterns"]))
for k in [x["key"] for x in a["patterns"][0]["algorithms"]]:
    cells = []
    for p in a["patterns"]:
        full = next(x for x in p["algorithms"] if x["key"] == "pack")["mean"]["benefitRatio"]
        v = next(x for x in p["algorithms"] if x["key"] == k)["mean"]["benefitRatio"]
        cells.append(f"{100 * v:.2f}" if k == "pack" else f"{100 * (v - full):+.2f}")
    nm = next(x for x in a["patterns"][0]["algorithms"] if x["key"] == k)["name"]
    w(f"| {nm} | " + " | ".join(cells) + " |")
w("\n(The PACK-DP row shows absolute benefit %.)\n")

# ----------------------------------------------------------------- solvers --
s = load("solvers.json")
w("## 4. Knapsack solvers\n")
for blk, title in [("scalingN", "Time (ms) vs n, C = 8192"), ("scalingC", "Time (ms) vs C, n = 2000"),
                   ("hardCorrelated", "Strongly-correlated instances: time (ms)"), ("hugeCapacity", "Huge capacity (C ≈ 10¹⁰): time (ms)")]:
    b = s[blk]
    w(f"### {title}\n")
    w("| Solver | " + " | ".join(f"{x:g}" for x in b["x"]) + " | log-log slope |")
    w("|---|" + "---:|" * (len(b["x"]) + 1))
    for al in b["algorithms"]:
        sl = al["logLogSlope"]
        w(f"| {al['name']} | " + " | ".join("–" if v is None else f"{v:.2f}" for v in al["ms"]) + f" | {'–' if sl is None else f'{sl:.2f}'} |")
    w("")
b = s["scalingN"]
w("### Table memory (KB) vs n, C = 8192\n")
w("| Solver | " + " | ".join(f"{x:g}" for x in b["x"]) + " |")
w("|---|" + "---:|" * len(b["x"]))
for al in b["algorithms"]:
    w(f"| {al['name']} | " + " | ".join("–" if v is None else f"{v:,.0f}" for v in al["memKB"]) + " |")
w("")
hb = next(al for al in s["hardCorrelated"]["algorithms"] if al["name"] == "bnb")
w("B&B nodes on strongly-correlated instances: " + ", ".join(
    f"n={x:g}: {int(v):,}" for x, v in zip(s["hardCorrelated"]["x"], hb["nodes"])) + " (cap 5·10⁷).\n")
f = s["fptasEps"]
w("### FPTAS accuracy / time\n")
w("| ε | guaranteed gap ≤ | observed gap (cache) | observed gap (hard) | time ms | memory KB |")
w("|---:|---:|---:|---:|---:|---:|")
for i, e in enumerate(f["eps"]):
    w(f"| {e:g} | {100 * e:g}% | {f['gapPct'][i]:.5f}% | {f['gapPctHard'][i]:.3f}% | {f['ms'][i]:.1f} | {f['memKB'][i]:,.0f} |")
w("")

o = load("optgap.json")
w(f"## 5. Price of approximation on real cache instances ({o['instances']} instances, ~{o['items'][0]:.0f} objects)\n")
w("Gap (%) to the best known solution; the LP slack column certifies how far the best known can be from the true optimum.\n")
w("| cache | " + " | ".join(f"{m['name']} mean / max" for m in o["methods"]) + " | bound v_b/OPT | LP slack max | B&B proved |")
w("|---|" + "---:|" * (len(o["methods"]) + 3))
for i, x in enumerate(o["x"]):
    w(f"| {100 * x:g}% | " + " | ".join(f"{m['meanGapPct'][i]:.3f} / {m['maxGapPct'][i]:.2f}" for m in o["methods"])
      + f" | {o['boundPct'][i]:.2f} | {o['lpSlackMaxPct'][i]:.3f} | {100 * o['provenFraction'][i]:.0f}% |")
w("")

ab = load("abr.json")
w(f"## 6. Multi-bitrate video (MCKP), {ab['videos']} videos × {len(ab['ladder'])} renditions, {ab['seeds']} seeds\n")
for fld, title in [("benefitRatio", "Benefit captured %"), ("hitRatio", "Request hit ratio %"),
                   ("byteHitRatio", "Byte hit ratio %"), ("costSavedPct", "Origin $ saved %")]:
    w(f"**{title}**\n")
    w("| Policy | " + " | ".join(f"{100 * x:g}%" for x in ab["x"]) + " |")
    w("|---|" + "---:|" * len(ab["x"]))
    for p in ab["policies"]:
        vals = p[fld]
        w(f"| {p['name']} | " + " | ".join(f"{v:.1f}" if fld == "costSavedPct" else f"{100 * v:.1f}" for v in vals) + " |")
    w("")
w(f"Largest MCKP solve: {ab['mckpMaxMs']:.0f} ms, {ab['mckpMemKB'] / 1024:.1f} MB.\n")

path = os.path.join(ROOT, "docs", "RESULTS.md")
with open(path, "w") as fh:
    fh.write("\n".join(out))
print("wrote", os.path.relpath(path, ROOT))
